import json
from pathlib import Path

folder = Path('data/table-review')
selection = json.loads((folder / 'selection.json').read_text(encoding='utf-8'))
lines = [
    '# Сокращение корпуса: документы с большими таблицами',
    '',
    'Критерий пользователя: исключить целиком документы, где большие таблицы занимают основную часть. Исходные файлы, прежние запуски и кеш сохранены.',
    '',
    'Отбор выполнен визуально по выборке: первая, последняя и три промежуточные страницы каждого документа; для коротких файлов — все доступные позиции. Для четырёх пограничных документов дополнительно просмотрено по 10 внутренних страниц. Это оценка по выборке, а не подсчёт всех табличных страниц. Контактные листы сохранены в data/table-review.',
    '',
    'В исключения вошли реестры, бухгалтерские формы, выписка ЕГРЮЛ и отчёты с преобладанием протяжённых таблиц. Документы с отдельными небольшими таблицами оставлены.',
    '',
    'Новый набор создаётся штатным API как отдельный корпус. Прежний кеш остаётся на диске; повторное использование всех страниц не гарантируется, поскольку идентификатор документа зависит от пути в корпусе.',
]
for key, title in [('excluded', 'Исключены'), ('retained', 'Оставлены')]:
    docs = selection[key]
    lines += ['', f'## {title}: {len(docs)} документов, {sum(d["pages"] for d in docs)} страниц', '', '| Документ | Страниц |', '|---|---:|']
    lines += [f'| {d["filename"]} | {d["pages"]} |' for d in docs]
if selection.get('new_run'):
    lines += ['', f'Текущий запуск: http://127.0.0.1:8765/?run_id={selection["new_run"]}', '']
Path('TABLE_SELECTION.md').write_text('\n'.join(lines), encoding='utf-8')
